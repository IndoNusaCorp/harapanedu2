// Game content per language. Answers are checked against `name` and optional `aliases`.

export type GameLocale = "id" | "en";

export const toGameLocale = (locale: string): GameLocale => (locale === "en" ? "en" : "id");

export interface GuessItem {
  emoji: string;
  name: string;
  aliases?: string[];
}

export const isCorrectGuess = (item: GuessItem, answer: string) => {
  const normalized = answer.toLowerCase().trim();
  return normalized === item.name || (item.aliases ?? []).includes(normalized);
};

